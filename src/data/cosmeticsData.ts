export type CosmeticCategory = 'COIN' | 'ACHIEVEMENT' | 'PREMIUM' | 'SPECIAL';
export type CosmeticRarity = 'COMMON' | 'RARE' | 'EPIC' | 'LEGENDARY' | 'ULTRA';

export interface SkinDesignFeatures {
  silhouette: string;
  material: string;
  uniqueFeature: string;
  vfx: string;
}

export interface PlayerSkinDefinition {
  id: string;
  name: string;
  category: CosmeticCategory;
  rarity: CosmeticRarity;
  costCoins?: number;
  priceRp?: number;
  priceDisplay?: string;
  isDefault?: boolean;
  isLockedByDefault?: boolean;
  allowPreviewWhenLocked: boolean;
  theme: string;
  description: string;
  lore: string;
  connectedSkinId?: string; // e.g. 'entity_ashen'
  designFeatures?: SkinDesignFeatures;
  unlockRequirement?: {
    type: 'default' | 'coins' | 'premium' | 'achievement' | 'secret' | 'story';
    text: string;
    achievementId?: string;
  };
}

export interface EntitySkinDefinition {
  id: string;
  name: string;
  category: CosmeticCategory;
  rarity: CosmeticRarity;
  costCoins?: number;
  priceRp?: number;
  priceDisplay?: string;
  isDefault?: boolean;
  isLockedByDefault?: boolean;
  allowPreviewWhenLocked: boolean;
  theme: string;
  description: string;
  lore: string;
  connectedPlayerSkinId?: string;
  designFeatures?: SkinDesignFeatures;
  unlockRequirement?: {
    type: 'default' | 'coins' | 'premium' | 'achievement' | 'secret' | 'story';
    text: string;
    achievementId?: string;
  };
}

export interface OrbCosmeticDefinition {
  id: string;
  name: string;
  rarity: CosmeticRarity;
  priceRp: number;
  priceDisplay: string;
  theme: string;
  description: string;
  lore: string;
  connectedSkinNames: string[];
  visualFeatures: string[];
}

export interface BundleDefinition {
  id: string;
  name: string;
  priceRp: number;
  priceDisplay: string;
  description: string;
  tag: string;
  itemIds: { type: 'player' | 'entity' | 'orb'; id: string }[];
}

